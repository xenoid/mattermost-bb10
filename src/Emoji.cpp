QVariantList catalog(const QString &query)
{
    const QString needle = query.trimmed().toLower();
    QVariantList list;
    QSet<QString> seen;
    for (int i = 0; kPairs[i].name; ++i) {
        const QString name = QString::fromLatin1(kPairs[i].name);
        if (!needle.isEmpty() && !name.contains(needle))
            continue;
        const QString g = keepOne(QString::fromUtf8(kPairs[i].utf8));
        if (g.isEmpty() || seen.contains(g))
            continue;
        seen.insert(g);
        QVariantMap row;
        row["name"] = name;
        row["glyph"] = g;
        row["type"] = QString("emoji");
        list.append(row);
    }
    return list;
}
