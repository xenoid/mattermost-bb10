void token(QString &text, const char *from, const char *utf8)
{
    const QString tok = QString::fromLatin1(from);
    const QString glyph = QString::fromUtf8(utf8);
    text.replace(QString(" ") + tok + " ", QString(" ") + glyph + " ");
    text.replace(QString(" ") + tok + "\n", QString(" ") + glyph + "\n");
    if (text == tok)
        text = glyph;
    else if (text.startsWith(tok + " "))
        text.replace(0, tok.size(), glyph);
    else if (text.endsWith(" " + tok))
        text.replace(text.size() - tok.size(), tok.size(), glyph);
}

