QString glyph(const QString &name)
{
    const QString g = keepOne(table().value(name));
    if (!g.isEmpty())
        return g;
    // Das rote Herz liegt nicht in der Geräteschrift. Funkeln ist das nächste Herz, das sie hat.
    if (name == QLatin1String("heart") || name == QLatin1String("hearts"))
        return keepOne(table().value(QLatin1String("sparkling_heart")));
    return QString();
}
QString apply(const QString &in)
{
    QString out;
    out.reserve(in.size());
    int i = 0;
    while (i < in.size()) {
        if (in.at(i) != QLatin1Char(':')) {
            out.append(in.at(i));
            ++i;
            continue;
        }
        const int j = in.indexOf(QLatin1Char(':'), i + 1);
        if (j < 0 || j - i > 40) {
            out.append(in.at(i));
            ++i;
            continue;
        }
        const QString name = in.mid(i + 1, j - i - 1);
        bool ok = !name.isEmpty();
        for (int c = 0; ok && c < name.size(); ++c) {
            const QChar ch = name.at(c);
            ok = ch.isDigit() || (ch >= QLatin1Char('a') && ch <= QLatin1Char('z'))
                || ch == QLatin1Char('_') || ch == QLatin1Char('+') || ch == QLatin1Char('-');
        }
        const QString g = ok ? glyph(name) : QString();
        if (g.isEmpty()) {
            out.append(in.at(i));
            ++i;
            continue;
        }
        out.append(g);
        i = j + 1;
    }
    token(out, ":-)", "\xf0\x9f\x98\x8a");
    token(out, ":-D", "\xf0\x9f\x98\x83");
    token(out, ";-)", "\xf0\x9f\x98\x89");
    token(out, ":-(", "\xf0\x9f\x98\x9e");
    token(out, ":-P", "\xf0\x9f\x98\x9b");
    token(out, ":-O", "\xf0\x9f\x98\xae");
    token(out, ":)", "\xf0\x9f\x98\x8a");
    token(out, ":D", "\xf0\x9f\x98\x83");
    token(out, ";)", "\xf0\x9f\x98\x89");
    token(out, ":(", "\xf0\x9f\x98\x9e");
    token(out, ":P", "\xf0\x9f\x98\x9b");
    token(out, ":O", "\xf0\x9f\x98\xae");
    token(out, "<3", "\xf0\x9f\x92\x96");
    return scrub(out);
}
