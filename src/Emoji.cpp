bool have(quint32 cp)
{
    int lo = 0;
    int hi = int(sizeof(kHave) / sizeof(kHave[0])) - 1;
    while (lo <= hi) {
        const int mid = (lo + hi) / 2;
        if (kHave[mid] == cp)
            return true;
        if (kHave[mid] < cp)
            lo = mid + 1;
        else
            hi = mid - 1;
    }
    return false;
}
bool ignorable(quint32 cp)
{
    return cp == 0xFE0E || cp == 0xFE0F || cp == 0x200D
        || (cp >= 0x1F3FB && cp <= 0x1F3FF);
}
quint32 readCp(const QString &s, int i, int *step)
{
    const QChar ch = s.at(i);
    if (ch.isHighSurrogate() && i + 1 < s.size() && s.at(i + 1).isLowSurrogate()) {
        *step = 2;
        return QChar::surrogateToUcs4(ch, s.at(i + 1));
    }
    *step = 1;
    return ch.unicode();
}
void appendCp(QString &out, quint32 cp)
{
    if (cp > 0xFFFF) {
        out.append(QChar(QChar::highSurrogate(cp)));
        out.append(QChar(QChar::lowSurrogate(cp)));
    } else {
        out.append(QChar(ushort(cp)));
    }
}
// Ein einzelnes Zeichen aus der Geräteschrift. Folgen aus mehreren Zeichen
// (Flaggen, ZWJ, Hautton) kann die Schrift nicht zusammensetzen.
QString keepOne(const QString &raw)
{
    quint32 only = 0;
    int n = 0;
    for (int i = 0; i < raw.size(); ) {
        int step = 1;
        const quint32 cp = readCp(raw, i, &step);
        i += step;
        if (ignorable(cp))
            continue;
        ++n;
        only = cp;
        if (n > 1)
            return QString();
    }
    if (n != 1 || !have(only))
        return QString();
    QString out;
    appendCp(out, only);
    return out;
}
QString scrub(const QString &in)
{
    QString out;
    out.reserve(in.size());
    for (int i = 0; i < in.size(); ) {
        int step = 1;
        const quint32 cp = readCp(in, i, &step);
        i += step;
        if (ignorable(cp))
            continue;
        if (cp > 0xFFFF && !have(cp))
            continue;
        appendCp(out, cp);
    }
    return out;
}
